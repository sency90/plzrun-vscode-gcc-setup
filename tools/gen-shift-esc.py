#!/usr/bin/env python3
"""templates/shift-esc.tsv 를 만든다: VSCode 에서 Esc 에 묶인 단축키 전부(명령, 조건).

vsc 는 이 목록마다 Shift+Esc 단축키를 하나씩 만들어 사용자 keybindings.json 에 넣는다.
목록 차례는 VSCode 가 Esc 를 고르는 우선순위 차례(뒤가 이김)를 따른다.
  1. VSCode 기본 단축키(기본 단축키 JSON 덤프의 차례)
  2. 내장 확장(app/extensions) 의 Esc 단축키
  3. 추가로 설치한 확장(~/.vscode/extensions) 의 Esc 단축키

사용법 (개발할 때만, vsc 자체는 python 이 필요 없다):
  python3 tools/gen-shift-esc.py <기본 단축키 덤프.json> <VSCode 앱 extensions 폴더> <~/.vscode/extensions> > templates/shift-esc.tsv
기본 단축키 덤프는 VSCode 의 "Preferences: Open Default Keyboard Shortcuts (JSON)" 와 같은 파일이다.
판별 덤프: https://github.com/codebling/vs-code-default-keybindings (macos.keybindings.json)
"""
import glob, json, os, re, sys


def load_jsonc(path):
    t = open(path, encoding="utf-8").read()
    t = re.sub(r"(?m)^\s*//.*$", "", t)
    return json.loads(t)


def is_escape(k):
    key = (k.get("mac") or k.get("key") or "").lower().replace(" ", "")
    return key == "escape"


def ext_rows(folder, label):
    rows = []
    for p in sorted(glob.glob(os.path.join(folder, "*", "package.json"))):
        try:
            d = json.load(open(p, encoding="utf-8"))
        except Exception:
            continue
        kb = (d.get("contributes") or {}).get("keybindings") or []
        if isinstance(kb, dict):
            kb = [kb]
        name = "%s.%s %s" % (d.get("publisher", "?"), d.get("name", "?"), d.get("version", ""))
        for k in kb:
            if is_escape(k):
                rows.append((label + ": " + name.strip(), k["command"], k.get("when", "")))
    return rows


def main(dump, app_ext, user_ext):
    head = open(dump, encoding="utf-8").readline().strip().lstrip("/ ").strip()
    rows = [("default", k["command"], k.get("when", "")) for k in load_jsonc(dump) if k["key"] == "escape"]
    rows += ext_rows(app_ext, "built-in")
    rows += ext_rows(user_ext, "extension")
    out = sys.stdout
    out.write("# Generated by tools/gen-shift-esc.py. Do not edit by hand.\n")
    out.write("# Every VSCode keybinding on Escape, in the order VSCode resolves them (a later line wins).\n")
    out.write("# vsc makes one shift+escape keybinding per line: same command, same when + the project folders.\n")
    out.write("# Source: %s\n" % head)
    srcs = sorted(set(r[0] for r in rows if r[0] != "default"))
    for s in srcs:
        out.write("# Source: %s\n" % s)
    out.write("# columns: command<TAB>when\n")
    for _, cmd, when in rows:
        if "\t" in cmd + when or "\n" in cmd + when:
            raise SystemExit("tab or line break in %r" % cmd)
        out.write("%s\t%s\n" % (cmd, when))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
